#!/usr/bin/env bash
# Подтягивает в существующую доску изменения шаблона и называет расхождения,
# которые подтянуть нельзя.
#
# Доска — разовая копия шаблона: обновление плагина обновляет скилы, но доску
# не трогает. Этот скрипт закрывает разрыв, не затирая то, что оператор
# настроил у себя.
#
# Что делает:
#   - недостающие файлы копирует;
#   - скрипты в scripts/ обновляет: они каноничны и живут в шаблоне;
#   - про остальные разошедшиеся файлы только сообщает, решает человек;
#   - называет скрипты, которые есть на доске и которых нет в шаблоне.
#
# Последнее — единственное расхождение, которое скрипт починить не может:
# писать в шаблон он не вправе, и всё, что ему остаётся, — произнести имя
# вслух. Сверяются только имена, содержимое не читается: доска живая, и
# расходиться с шаблоном содержимым для неё нормально, а вот скрипт, которого
# в шаблоне нет вовсе, — это схема, выросшая на доске и не вернувшаяся в
# плагин, из которого доски разворачивают.
#
# Сверка намеренно сужена до scripts/: каноничность границы уже проведена
# самим этим скриптом — скрипты принадлежат шаблону, остальное принадлежит
# оператору. Проверка, которая срабатывает на любом отличающемся файле живой
# доски, срабатывала бы всегда, а срабатывающую всегда проверку начинают
# пролистывать — вместе с настоящими находками.
#
# Использование:
#   upgrade-board.sh [--dry-run] [каталог]    по умолчанию ~/fleetdeck/board
#
# --dry-run печатает тот же отчёт, ничего не меняя: посмотреть, что разошлось,
# не чиня этого прямо сейчас. Код возврата у него всегда нулевой — это отчёт,
# а не заслон; заслон, роняющий чужой прогон, выключают целиком вместе с
# пользой.
#
# Доске, которая лежит в другом месте, каталог передают аргументом: он
# записан в board.path файла ~/.config/fleetdeck/config.yaml, а у второго и
# следующих флотов — в board.path их записи в списке fleets. Скрипт работает
# с одной доской за раз; доски нескольких флотов обновляются по очереди.
set -euo pipefail

dry_run=0
target=""
while [ $# -gt 0 ]; do
    case "$1" in
        --dry-run)
            dry_run=1
            ;;
        -*)
            printf 'неизвестный аргумент: %s\n' "$1" >&2
            printf 'использование: upgrade-board.sh [--dry-run] [каталог]\n' >&2
            exit 2
            ;;
        *)
            if [ -n "$target" ]; then
                printf 'лишний аргумент: %s\n' "$1" >&2
                printf 'скрипт работает с одной доской за раз\n' >&2
                exit 2
            fi
            target="$1"
            ;;
    esac
    shift
done
target="${target:-$HOME/fleetdeck/board}"

here="$(cd "$(dirname "$0")" && pwd -P)"
template="$here/../templates/board"

if [ ! -d "$template" ]; then
    printf 'не найден шаблон доски: %s\n' "$template" >&2
    exit 1
fi
if [ ! -d "$target/cards" ]; then
    printf 'не похоже на каталог доски: %s\n' "$target" >&2
    printf 'для новой доски используйте bootstrap-board.sh\n' >&2
    exit 1
fi

changed=0
diverged=0
ahead=0

# Доска отстала от шаблона: недостающие файлы и обновление каноничных скриптов.
while IFS= read -r rel; do
    src="$template/$rel"
    dst="$target/$rel"
    if [ ! -e "$dst" ]; then
        if [ "$dry_run" -eq 1 ]; then
            printf 'не хватает файла: %s\n' "$rel"
        else
            mkdir -p "$(dirname "$dst")"
            cp "$src" "$dst"
            printf 'добавлен файл:   %s\n' "$rel"
        fi
        changed=$((changed + 1))
        continue
    fi
    if cmp -s "$src" "$dst"; then
        continue
    fi
    case "$rel" in
        scripts/*.py)
            if [ "$dry_run" -eq 1 ]; then
                printf 'отстал скрипт:    %s\n' "$rel"
            else
                cp "$src" "$dst"
                printf 'обновлён скрипт: %s\n' "$rel"
            fi
            changed=$((changed + 1))
            ;;
        *)
            printf 'разошёлся, не трогаю: %s\n' "$rel"
            diverged=$((diverged + 1))
            ;;
    esac
done < <(cd "$template" && find . -type f ! -name .gitkeep | sed 's|^\./||' | sort)

# Доска ушла вперёд шаблона: скрипты, которых в шаблоне нет.
#
# Только файлы верхнего уровня scripts/: __pycache__, который остаётся от
# прогона тестов доски, — каталог, и в сверку не попадает. Он в .gitignore
# самой доски, то есть её частью не является, и называть его расхождением
# значило бы срабатывать на каждой доске, где хоть раз запускали тесты.
if [ -d "$target/scripts" ]; then
    while IFS= read -r name; do
        [ -n "$name" ] || continue
        if [ ! -e "$template/scripts/$name" ]; then
            printf 'нет в шаблоне: scripts/%s\n' "$name"
            ahead=$((ahead + 1))
        fi
    done < <(cd "$target/scripts" && find . -maxdepth 1 -type f ! -name .DS_Store | sed 's|^\./||' | sort)
fi

if [ "$changed" -eq 0 ] && [ "$diverged" -eq 0 ] && [ "$ahead" -eq 0 ]; then
    printf 'доска уже соответствует шаблону: %s\n' "$target"
    exit 0
fi

if [ "$ahead" -gt 0 ]; then
    printf '\nСкрипты, которых нет в шаблоне, — это доска, ушедшая вперёд плагина.\n'
    printf 'Скрипт их не трогает: вернуть их в шаблон может только человек, через\n'
    printf 'репозиторий плагина.\n'
fi

if [ "$dry_run" -eq 1 ]; then
    printf '\nничего не изменено: это режим просмотра.\n'
    printf 'Чтобы применить, повторите вызов без --dry-run.\n'
    exit 0
fi

if [ "$changed" -eq 0 ]; then
    exit 0
fi

# Доказываем, что обновлённое работает, а не просто скопировалось.
cd "$target"
printf '\nпроверка валидатора: '
python3 scripts/validate_cards.py
printf 'проверка тестов:    '
( cd scripts && python3 -m unittest test_validate_cards 2>&1 | tail -1 )

printf '\nизменения не закоммичены: подпись попросит PIN, а скрипт может идти\n'
printf 'без человека. Зафиксируйте сами либо оставьте ближайшей уборке флота.\n'
